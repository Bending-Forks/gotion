const timeout = time.Second

// callee is a fake service behind the transport: it answers the attempts in turn, the last answer repeating.
type callee struct {
	answers []func(*http.Request) (*http.Response, error)
	calls   int
}

func (c *callee) RoundTrip(req *http.Request) (*http.Response, error) {
	answer := c.answers[min(c.calls, len(c.answers)-1)]
	c.calls++
	return answer(req)
}

func reply(status int, body string) func(*http.Request) (*http.Response, error) {
	return func(*http.Request) (*http.Response, error) {
		return &http.Response{StatusCode: status, Status: http.StatusText(status), Header: http.Header{}, Body: io.NopCloser(strings.NewReader(body))}, nil
	}
}

func refuse(*http.Request) (*http.Response, error) { return nil, syscall.ECONNREFUSED }

// after answers like a transport does: with the reply once d has passed, or with the error of the request's context first.
func after(d time.Duration, answer func(*http.Request) (*http.Response, error)) func(*http.Request) (*http.Response, error) {
	return func(req *http.Request) (*http.Response, error) {
		select {
		case <-time.After(d):
			return answer(req)
		case <-req.Context().Done():
			return nil, req.Context().Err()
		}
	}
}

func hang(req *http.Request) (*http.Response, error) {
	<-req.Context().Done()
	return nil, req.Context().Err()
}

func newClient(c *callee) *Client {
	client := New(timeout, gobreaker.Settings{Name: "membership"})
	client.http.Transport = c
	return client
}

func get(t *testing.T, client *Client) (*http.Response, error) {
	t.Helper()
	req, err := http.NewRequestWithContext(t.Context(), http.MethodGet, "http://membership/internal/v1/roles", nil)
	if err != nil {
		t.Fatal(err)
	}
	return client.Do(req)
}

func TestFailedCallsAreRefused(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		name        string
		answers     []func(*http.Request) (*http.Response, error)
		wantCalls   int
		wantElapsed time.Duration
	}{
		{name: "a refused connection is retried once, then refused", answers: []func(*http.Request) (*http.Response, error){refuse}, wantCalls: 2},
		{name: "a server error is retried once, then refused", answers: []func(*http.Request) (*http.Response, error){reply(http.StatusServiceUnavailable, "")}, wantCalls: 2},
		{name: "a callee that never answers is refused at the timeout", answers: []func(*http.Request) (*http.Response, error){hang}, wantCalls: 1, wantElapsed: timeout},
		{name: "a callee slower than the timeout is refused at the timeout", answers: []func(*http.Request) (*http.Response, error){after(2*timeout, reply(http.StatusOK, "{}"))}, wantCalls: 1, wantElapsed: timeout},
		{name: "the retry shares the timeout of the call", answers: []func(*http.Request) (*http.Response, error){after(timeout*6/10, reply(http.StatusInternalServerError, "")), hang}, wantCalls: 2, wantElapsed: timeout},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			synctest.Test(t, func(t *testing.T) {
				c := &callee{answers: tt.answers}
				start := time.Now()

				resp, err := get(t, newClient(c))

				if err == nil {
					resp.Body.Close()
					t.Fatalf("Do answered %s, want an error", resp.Status)
				}
				if c.calls != tt.wantCalls {
					t.Errorf("callee got %d calls, want %d", c.calls, tt.wantCalls)
				}
				if elapsed := time.Since(start); elapsed != tt.wantElapsed {
					t.Errorf("refused after %v, want %v", elapsed, tt.wantElapsed)
				}
			})
		})
	}
}

func TestAnswersAreReturned(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		name      string
		answers   []func(*http.Request) (*http.Response, error)
		want      int
		wantCalls int
	}{
		{name: "an answer is returned with its body", answers: []func(*http.Request) (*http.Response, error){reply(http.StatusOK, `{"role":"Editor"}`)}, want: http.StatusOK, wantCalls: 1},
		{name: "a client error is an answer of the callee, not retried", answers: []func(*http.Request) (*http.Response, error){reply(http.StatusNotFound, `{"role":"Editor"}`)}, want: http.StatusNotFound, wantCalls: 1},
		{name: "a call that fails once is answered by its retry", answers: []func(*http.Request) (*http.Response, error){reply(http.StatusBadGateway, ""), reply(http.StatusOK, `{"role":"Editor"}`)}, want: http.StatusOK, wantCalls: 2},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			synctest.Test(t, func(t *testing.T) {
				c := &callee{answers: tt.answers}

				resp, err := get(t, newClient(c))
				if err != nil {
					t.Fatalf("Do: %v", err)
				}
				defer resp.Body.Close()

				// The body is read after Do has returned, as the client generated by oapi-codegen does.
				body, err := io.ReadAll(resp.Body)
				if err != nil {
					t.Fatalf("read body: %v", err)
				}
				if resp.StatusCode != tt.want || string(body) != `{"role":"Editor"}` {
					t.Errorf("Do answered %d %q, want %d with the body of the callee", resp.StatusCode, body, tt.want)
				}
				if c.calls != tt.wantCalls {
					t.Errorf("callee got %d calls, want %d", c.calls, tt.wantCalls)
				}
			})
		})
	}
}

func TestRetryResendsTheBody(t *testing.T) {
	t.Parallel()
	synctest.Test(t, func(t *testing.T) {
		const query = `{"workspaces":["w1","w2"]}`
		var bodies []string
		record := func(answer func(*http.Request) (*http.Response, error)) func(*http.Request) (*http.Response, error) {
			return func(req *http.Request) (*http.Response, error) {
				body, err := io.ReadAll(req.Body)
				if err != nil {
					t.Fatal(err)
				}
				bodies = append(bodies, string(body))
				return answer(req)
			}
		}
		client := newClient(&callee{answers: []func(*http.Request) (*http.Response, error){record(reply(http.StatusServiceUnavailable, "")), record(reply(http.StatusOK, "{}"))}})
		req, err := http.NewRequestWithContext(t.Context(), http.MethodPost, "http://account/internal/v1/workspaces", bytes.NewReader([]byte(query)))
		if err != nil {
			t.Fatal(err)
		}

		resp, err := client.Do(req)
		if err != nil {
			t.Fatalf("Do: %v", err)
		}
		resp.Body.Close()

		if len(bodies) != 2 || bodies[0] != query || bodies[1] != query {
			t.Errorf("callee got bodies %q, want the query twice", bodies)
		}
	})
}

func TestCircuitBreaker(t *testing.T) {
	t.Parallel()
	synctest.Test(t, func(t *testing.T) {
		c := &callee{answers: []func(*http.Request) (*http.Response, error){refuse}}
		client := newClient(c)

		// The defaults of gobreaker: the circuit opens after more than 5 consecutive failed calls.
		for range 6 {
			if resp, err := get(t, client); err == nil {
				resp.Body.Close()
				t.Fatal("a failed call was answered")
			}
		}
		calls := c.calls
		if _, err := get(t, client); !errors.Is(err, gobreaker.ErrOpenState) {
			t.Fatalf("with the circuit open Do returned %v, want %v", err, gobreaker.ErrOpenState)
		}
		if c.calls != calls {
			t.Errorf("the callee was called with the circuit open")
		}

		// Once the open period of gobreaker, 60 s, has passed, one call goes through and closes the circuit.
		time.Sleep(61 * time.Second)
		c.answers = []func(*http.Request) (*http.Response, error){reply(http.StatusOK, "{}")}
		resp, err := get(t, client)
		if err != nil {
			t.Fatalf("the trial call was refused: %v", err)
		}
		resp.Body.Close()
		if state := client.breaker.State(); state != gobreaker.StateClosed {
			t.Errorf("after a successful trial call the circuit is %v, want closed", state)
		}
	})
}

func TestCallsTheCallerGivesUpKeepTheCircuitClosed(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		name   string
		giveUp func(context.Context) (context.Context, context.CancelFunc)
		want   error
	}{
		{name: "canceled by the caller", giveUp: func(ctx context.Context) (context.Context, context.CancelFunc) {
			ctx, cancel := context.WithCancel(ctx)
			time.AfterFunc(timeout/4, cancel)
			return ctx, cancel
		}, want: context.Canceled},
		{name: "past the deadline of the caller", giveUp: func(ctx context.Context) (context.Context, context.CancelFunc) {
			return context.WithTimeout(ctx, timeout/4)
		}, want: context.DeadlineExceeded},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			synctest.Test(t, func(t *testing.T) {
				// The callee answers within the timeout of the client, but after the caller has given up.
				client := newClient(&callee{answers: []func(*http.Request) (*http.Response, error){after(timeout/2, reply(http.StatusOK, "{}"))}})

				for range 10 {
					ctx, cancel := tt.giveUp(t.Context())
					req, err := http.NewRequestWithContext(ctx, http.MethodGet, "http://membership/internal/v1/roles", nil)
					if err != nil {
						t.Fatal(err)
					}
					_, err = client.Do(req)
					cancel()
					if !errors.Is(err, tt.want) {
						t.Fatalf("Do returned %v, want %v", err, tt.want)
					}
				}
				resp, err := get(t, client)
				if err != nil {
					t.Fatalf("after calls %s, a call with the whole timeout was refused: %v", tt.name, err)
				}
				resp.Body.Close()
			})
		})
	}
}

func TestClientErrorsKeepTheCircuitClosed(t *testing.T) {
	t.Parallel()
	synctest.Test(t, func(t *testing.T) {
		client := newClient(&callee{answers: []func(*http.Request) (*http.Response, error){reply(http.StatusNotFound, "")}})

		for range 10 {
			resp, err := get(t, client)
			if err != nil {
				t.Fatalf("Do: %v", err)
			}
			resp.Body.Close()
		}
		if state := client.breaker.State(); state != gobreaker.StateClosed {
			t.Errorf("after client errors the circuit is %v, want closed", state)
		}
	})
}

func TestRealServer(t *testing.T) {
	t.Parallel()

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = io.WriteString(w, `{"role":"Admin"}`)
	}))
	// The interface of the clients oapi-codegen generates, which take the Client with WithHTTPClient.
	var doer interface {
		Do(*http.Request) (*http.Response, error)
	} = New(timeout, gobreaker.Settings{Name: "membership"})

	req, err := http.NewRequestWithContext(t.Context(), http.MethodGet, server.URL, nil)
	if err != nil {
		t.Fatal(err)
	}
	resp, err := doer.Do(req)
	if err != nil {
		t.Fatalf("Do: %v", err)
	}
	body, err := io.ReadAll(resp.Body)
	resp.Body.Close()
	if err != nil || string(body) != `{"role":"Admin"}` {
		t.Errorf("read %q, %v, want the body of the server", body, err)
	}

	server.Close()
	if resp, err := doer.Do(req); err == nil {
		resp.Body.Close()
		t.Error("a closed server was answered")
	}
}
